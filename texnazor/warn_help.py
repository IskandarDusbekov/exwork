from typing import List


def _h(why: str, todo: List[str]) -> dict:
    return {"why": why, "todo": todo}


_UNDO = "Фикрингиз ўзгарса — «Бекор қилиш — файлдагидек» тугмасини босинг."


def _by_fix(w: dict):
    fix = w.get("fix")
    if fix == "drop_const":
        amt = f" — тахминан <b>{w['amount']}</b> сўм" if w.get("amount") else ""
        return _h(f"Ҳажм ёзилмаган далолатнома ҳам 0 эмас, шу сон (устамалар ва ҚҚС билан){amt} кўрсатади. "
                  "Ҳар янги далолатномада бу сон яна қўшилади, яъни бир неча марта тўланиб кетади.",
                  ["Сон яхлитлаш ёки тасодифий бўлса — пастдаги <b>«Бу сонни далолатномаларда ҳисобламаслик»</b> тугмасини "
                   "босинг. Офёрта жами ўзгармайди, бу сон «Остатка»да қолади.",
                   "Сон атайлаб қўшилган бўлса (масалан, алоҳида иш учун) — смета тузувчидан уни Excel'да алоҳида иш "
                   "қатори қилишни сўранг ва файлни қайта юкланг."])
    if fix == "drop_const_on":
        return _h("Офёрта жами файлдагидек қолди. Бу сон ҳеч бир далолатномага тушмагани учун «Остатка»да кўриниб туради.",
                  ["Ҳеч нарса қилиш шарт эмас.", _UNDO])
    if fix == "prop_res":
        return _h("Бу ресурсларнинг пули ўз иши ҳажмига қараб ўзгармайди: далолатнома бўш бўлса ҳам пул чиқади, "
                  "ишнинг ярмини ёзсангиз ҳам тўлиқ суммаси тушади.",
                  ["<b>«Формулани тузатиш»</b> — ресурс ўз иши ҳажмига уланади. Офёрта жами ҳам ўзгаради (жадвалда олдин ва "
                   "кейин кўрсатилган).",
                   "<b>«Мутаносиб қилиш»</b> — формулага тегилмайди, офёрта жами ўзгармайди; фақат далолатномада ресурс "
                   "ўз иши ҳажмига мутаносиб ҳисобланади.",
                   "Ёки смета тузувчи формулани Excel'да тузатиб, файлни қайта юкласин."])
    if fix in ("prop_res_on", "relink_on"):
        return _h("Энди далолатномада бу ресурслар ўз иши ҳажмига қараб ҳисобланади.", ["Ҳеч нарса қилиш шарт эмас.", _UNDO])
    return None


