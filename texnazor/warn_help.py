def explain(w: dict) -> dict:
    """Ogohlantirishga ``why`` (матн, HTML) va ``todo`` (рўйхат, HTML) qo'shadi; topilmasa — o'zgarmaydi."""
    h = _by_fix(w)
    if w.get("fix") == "drop_const" and w.get("items"):  # «Нима бўлди» — aniq katak va formula bilan
        cell, old = w["items"][0][:2]
        more = f" (яна {w['count'] - 1} та формулада ҳам шундай)" if w.get("count", 1) > 1 else ""
        h = dict(h, text=f"Excel'даги сводка формуласига смета тузувчи қўлда сон қўшган: {cell} катакда «{old}»{more}. "
                         "Бу сон бирорта ишга боғланмаган — ишлар йиғиндисига шунчаки қўшиб қўйилган.")
    if h is None:
        title = w.get("title") or ""
        h = next((x for key, x in _BY_TITLE if key in title), None)
    return dict(w, **h) if h else w
