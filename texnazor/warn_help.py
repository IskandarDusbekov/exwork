def _h(why: str, todo: List[str]) -> dict:
    return {"why": why, "todo": todo}


_UNDO = _noop("Фикрингиз ўзгарса — «Бекор қилиш — файлдагидек» тугмасини босинг.")


def _by_fix(w: dict):
    fix = w.get("fix")
    if fix == "drop_const":
        amt = _noop(" — тахминан <b>{0}</b> сўм").format(w['amount']) if w.get("amount") else ""
        return _h(_noop("Ҳажм ёзилмаган далолатнома ҳам 0 эмас, шу сон (устамалар ва ҚҚС билан){0} кўрсатади. Ҳар янги далолатномада бу сон яна қўшилади, яъни бир неча марта тўланиб кетади.").format(amt),
                  [_noop("Сон яхлитлаш ёки тасодифий бўлса — пастдаги <b>«Бу сонни далолатномаларда ҳисобламаслик»</b> тугмасини "
                   "босинг. Офёрта жами ўзгармайди, бу сон «Остатка»да қолади."),
                   _noop("Сон атайлаб қўшилган бўлса (масалан, алоҳида иш учун) — смета тузувчидан уни Excel'да алоҳида иш "
                   "қатори қилишни сўранг ва файлни қайта юкланг.")])
    if fix == "drop_const_on":
        return _h(_noop("Офёрта жами файлдагидек қолди. Бу сон ҳеч бир далолатномага тушмагани учун «Остатка»да кўриниб туради."),
                  [_noop("Ҳеч нарса қилиш шарт эмас."), _UNDO])
    if fix == "prop_res":
        return _h(_noop("Бу ресурсларнинг пули ўз иши ҳажмига қараб ўзгармайди: далолатнома бўш бўлса ҳам пул чиқади, "
                  "ишнинг ярмини ёзсангиз ҳам тўлиқ суммаси тушади."),
                  [_noop("<b>«Формулани тузатиш»</b> — ресурс ўз иши ҳажмига уланади. Офёрта жами ҳам ўзгаради (жадвалда олдин ва "
                   "кейин кўрсатилган)."),
                   _noop("<b>«Мутаносиб қилиш»</b> — формулага тегилмайди, офёрта жами ўзгармайди; фақат далолатномада ресурс "
                   "ўз иши ҳажмига мутаносиб ҳисобланади."),
                   _noop("Ёки смета тузувчи формулани Excel'да тузатиб, файлни қайта юкласин.")])
    if fix in ("prop_res_on", "relink_on"):
        return _h(_noop("Энди далолатномада бу ресурслар ўз иши ҳажмига қараб ҳисобланади."), [_noop("Ҳеч нарса қилиш шарт эмас."), _UNDO])
    return None


