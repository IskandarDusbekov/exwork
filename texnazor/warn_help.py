def explain(w: dict) -> dict:
    """Ogohlantirishga ``why`` (матн, HTML) va ``todo`` (рўйхат, HTML) qo'shadi; topilmasa — o'zgarmaydi."""
    h = _by_fix(w)
    if w.get("fix") == "drop_const" and w.get("items"):  # «Нима бўлди» — aniq katak va formula bilan
        cell, old = w["items"][0][:2]
        more = _noop(" (яна {0} та формулада ҳам шундай)").format(w['count'] - 1) if w.get("count", 1) > 1 else ""
        h = dict(h, text=_noop("Excel'даги сводка формуласига смета тузувчи қўлда сон қўшган: {0} катакда «{1}»{2}. Бу сон бирорта ишга боғланмаган — ишлар йиғиндисига шунчаки қўшиб қўйилган.").format(cell, old, more))
    if h is None:
        title = w.get("title") or ""
        h = next((x for key, x in _BY_TITLE if key in title), None)
    if not h:
        return w
    # матнлар асосий тилда (``_noop``) — кўрсатишда жорий тилга
    h = {k: ([ui(t) for t in v] if isinstance(v, list) else ui(v)) for k, v in h.items()}
    return dict(w, **h)
