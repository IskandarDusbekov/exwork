def help_texts() -> dict:
    """``HELP`` + панелда ўзгартирилгани (6-босқич, ``SiteSetting`` "help_texts"). Бўш қолдирилган майдон — коддагиси."""
    from panel import conf
    over = conf.raw("help_texts", {})
    if not isinstance(over, dict):
        over = {}
    out = {}
    for k, base in HELP.items():
        o = over.get(k)
        # жорий тилда: коддаги матн — таржимаси; панелда ўзгартирилгани — таржимаси бўлса (бўлмаса ўзи)
        out[k] = tuple(ui(o[i] if isinstance(o, (list, tuple)) and i < len(o) and str(o[i]).strip() else base[i])
                       for i in range(3))
    return out


def help_groups():
    """/help/ саҳифаси учун: [(бўлим, [{key, title, what, todo}]), …]."""
    texts = help_texts()
    return [(_(title), [{"key": k, "title": texts[k][0], "what": texts[k][1], "todo": texts[k][2]} for k in keys])
            for title, keys in HELP_GROUPS]


